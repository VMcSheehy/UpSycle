// Applied from next.config.ts. Checkout is a redirect to Stripe, and the
// Customer Portal is too, so Stripe's hosts are allowed for frames and
// connections without opening the rest of the web.

export function securityHeaders(): Array<{ key: string; value: string }> {
  const contentSecurityPolicy = [
    "default-src 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
    "img-src 'self' data: blob: https:",
    "font-src 'self' data:",
    "style-src 'self' 'unsafe-inline'",
    "script-src 'self' 'unsafe-inline' https://*.stripe.com",
    "connect-src 'self' https://*.stripe.com https://*.link.com",
    "frame-src https://*.stripe.com https://*.link.com",
  ].join("; ");

  return [
    { key: "Content-Security-Policy", value: contentSecurityPolicy },
    { key: "X-Content-Type-Options", value: "nosniff" },
    { key: "X-Frame-Options", value: "DENY" },
    { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
    { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
    { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
  ];
}
